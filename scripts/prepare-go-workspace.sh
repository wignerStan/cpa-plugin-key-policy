#!/usr/bin/env bash
set -euo pipefail

repo_root="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
cd -- "${repo_root}"
infra_go_dir="${INFRA_GO_DIR:-${HOME}/infra/go}"
# Keep relative paths relative to the repository so CI container builds can
# use the same workspace when the checkout is mounted at a different path.
case "${infra_go_dir}" in
  /*|[A-Za-z]:/*|./*|../*) ;;
  *) infra_go_dir="./${infra_go_dir}" ;;
esac
workspace_file="${repo_root}/go.work"
marker='// Generated by scripts/prepare-go-workspace.sh.'
if [[ -f "${workspace_file}" ]] && [[ "$(head -n 1 "${workspace_file}")" != "${marker}" ]]; then
  printf 'go.work is user-managed; add the config/file and files/notify replacements there instead.\n' >&2
  exit 1
fi

for module in config/file files/notify; do
  if [[ ! -f "${infra_go_dir}/${module}/go.mod" ]]; then
    printf 'missing direct infra module: %s (set INFRA_GO_DIR)\n' "${infra_go_dir}/${module}" >&2
    exit 1
  fi
done

workspace_tmp="$(mktemp "${repo_root}/.go-work.XXXXXX")"
trap 'rm -f -- "${workspace_tmp}"' EXIT
printf '%s\n\ngo 1.23.0\n\nuse .\n' "${marker}" > "${workspace_tmp}"
for module in config/file files/notify; do
  GOWORK="${workspace_tmp}" go work edit "-replace=github.com/wignerStan/infra/go/${module}=${infra_go_dir}/${module}"
done
mv -- "${workspace_tmp}" "${workspace_file}"
